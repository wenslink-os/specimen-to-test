'use strict';
// Bundles packs/*.json into site/samples.js so the page works without fetching files.
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.join(__dirname, '..');

function render() {
  const dir = path.join(ROOT, 'packs');
  const packs = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
  return '// Generated by tools/build-site.js from packs/*.json. Do not edit by hand.\nwindow.SPECIMEN_SAMPLES = ' + JSON.stringify(packs, null, 1) + ';\n';
}

if (require.main === module) {
  fs.writeFileSync(path.join(ROOT, 'site', 'samples.js'), render());
  console.log('wrote site/samples.js');
}
module.exports = { render };
